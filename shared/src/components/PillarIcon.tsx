export function hasPillarIcon(key: string) {
  return key in PATHS;
}

export function PillarIcon({ pillarKey, size = 20 }: { pillarKey: string; size?: number }) {
  const path = PATHS[pillarKey];
  if (!path) return null;
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
    >
      {path}
    </svg>
  );
}
